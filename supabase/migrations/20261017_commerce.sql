-- Apply once to the SAME Supabase project used by Orzu and this API.
-- Safe to rerun. Money, referrals and allowances are only mutated by service-role RPCs.
begin;

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    telegram_id bigint not null unique,
    first_name text not null default '', last_name text, username text,
    language_code text default 'uz', is_premium boolean default false,
    role text not null default 'user', is_active boolean not null default true,
    balance numeric not null default 0, created_at timestamptz not null default now()
);
alter table public.users add column if not exists bot_profiles jsonb not null default '{}';
create unique index if not exists users_telegram_id_commerce_idx on public.users(telegram_id);

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    user_id bigint not null, amount numeric not null,
    receipt_file_id text, username text, full_name text,
    status text not null default 'pending', created_at timestamptz not null default now()
);
alter table public.payments add column if not exists purpose text not null default 'topup';
alter table public.payments add column if not exists receipt_hash text;
alter table public.payments add column if not exists receipt_tx text;
alter table public.payments add column if not exists review jsonb not null default '{}';
create unique index if not exists payments_live_hash_idx on public.payments(receipt_hash)
    where receipt_hash is not null and status in ('pending', 'completed');
create unique index if not exists payments_live_tx_idx on public.payments(receipt_tx)
    where receipt_tx is not null and status in ('pending', 'completed');

create table if not exists public.statistics (
    id bigint generated by default as identity primary key,
    user_id bigint not null, action_type text not null, amount numeric default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.commerce_receipt_keys (
    kind text not null check (kind in ('hash', 'tx')), key text not null,
    user_id bigint not null, payment_id text, created_at timestamptz not null default now(),
    primary key(kind, key)
);
-- Keep historical receipt protection when retiring Orzu's local SQLite cache.
insert into commerce_receipt_keys(kind, key, user_id)
    select 'hash', substring(action_type from length('receipt_hash_') + 1), user_id
    from statistics where action_type like 'receipt\_hash\_%' escape '\'
    on conflict do nothing;
insert into commerce_receipt_keys(kind, key, user_id)
    select 'tx', substring(action_type from length('receipt_tx_') + 1), user_id
    from statistics where action_type like 'receipt\_tx\_%' escape '\'
    on conflict do nothing;

create table if not exists public.commerce_accounts (
    user_id bigint primary key,
    referrer_id bigint references public.commerce_accounts(user_id),
    referral_confirmed boolean not null default false,
    rewarded_batches integer not null default 0,
    subscription_start timestamptz, subscription_end timestamptz,
    subscription_used integer not null default 0 check (subscription_used between 0 and 10),
    created_at timestamptz not null default now(),
    check (referrer_id is null or referrer_id <> user_id)
);
-- Existing customers cannot become new referrals when this feature is deployed.
insert into public.commerce_accounts(user_id) select telegram_id from public.users
on conflict do nothing;
create index if not exists commerce_referrers_idx on public.commerce_accounts(referrer_id)
    where referral_confirmed;

create table if not exists public.commerce_grants (
    id uuid primary key default gen_random_uuid(),
    user_id bigint not null references public.commerce_accounts(user_id),
    service text not null check (service in ('presentation', 'course')),
    batch integer not null, remaining integer not null check (remaining >= 0),
    expires_at timestamptz, created_at timestamptz not null default now(),
    unique(user_id, service, batch)
);
create table if not exists public.commerce_charges (
    id uuid primary key,
    user_id bigint not null references public.commerce_accounts(user_id),
    service text not null check (service in ('presentation', 'course', 'referat', 'article', 'design', 'obyektivka')),
    source text not null check (source in ('balance', 'subscription', 'referral')),
    amount numeric not null default 0 check (amount >= 0),
    grant_id uuid references public.commerce_grants(id), subscription_start timestamptz,
    status text not null default 'reserved' check (status in ('reserved', 'completed', 'refunded')),
    lease_until timestamptz not null default now() + interval '3 minutes',
    created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.commerce_jobs (
    id uuid primary key references public.commerce_charges(id),
    user_id bigint not null, service text not null,
    payload jsonb not null,
    status text not null default 'queued' check (status in ('queued', 'processing', 'completed', 'failed')),
    attempts integer not null default 0,
    worker_id uuid, lease_until timestamptz,
    result jsonb, error text,
    created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create or replace function public.commerce_register(
    p_user_id bigint, p_first_name text default '', p_last_name text default null,
    p_username text default null, p_referrer_id bigint default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_new boolean;
begin
    if p_user_id <= 0 then raise exception 'invalid_user'; end if;
    perform pg_advisory_xact_lock(p_user_id);
    select not exists(select 1 from users where telegram_id = p_user_id) into v_new;
    insert into users(telegram_id, first_name, last_name, username)
    values(p_user_id, coalesce(p_first_name, ''), p_last_name, p_username)
    on conflict (telegram_id) do update set
        first_name = excluded.first_name, last_name = excluded.last_name, username = excluded.username;
    insert into commerce_accounts(user_id, referrer_id)
    values(p_user_id, case when v_new and p_referrer_id <> p_user_id and
        exists(select 1 from commerce_accounts where user_id = p_referrer_id)
        then p_referrer_id else null end)
    on conflict do nothing;
    return jsonb_build_object('created', v_new);
end $$;

create or replace function public.commerce_confirm_referral(p_user_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_ref bigint; v_count integer; v_batches integer; v_awarded integer; v_i integer;
begin
    select referrer_id into v_ref from commerce_accounts where user_id = p_user_id;
    if v_ref is null then return jsonb_build_object('awarded', false); end if;
    -- Serialize all confirmations for one inviter. Never award twice on repeated /start.
    perform 1 from commerce_accounts where user_id = v_ref for update;
    update commerce_accounts set referral_confirmed = true
        where user_id = p_user_id and not referral_confirmed;
    if not found then return jsonb_build_object('awarded', false); end if;
    select count(*)::integer into v_count from commerce_accounts
        where referrer_id = v_ref and referral_confirmed;
    v_batches := v_count / 5;
    select rewarded_batches into v_awarded from commerce_accounts where user_id = v_ref;
    if v_batches > v_awarded then
        for v_i in (v_awarded + 1)..v_batches loop
            insert into commerce_grants(user_id, service, batch, remaining, expires_at)
                values(v_ref, 'presentation', v_i, 5, now() + interval '1 month'),
                      (v_ref, 'course', v_i, 1, null);
        end loop;
        update commerce_accounts set rewarded_batches = v_batches where user_id = v_ref;
    end if;
    return jsonb_build_object('awarded', v_batches > v_awarded, 'referrer_id', v_ref,
        'confirmed', v_count, 'batches', v_batches - v_awarded);
end $$;

create or replace function public.commerce_status(p_user_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare a commerce_accounts%rowtype; v_refs integer; v_free integer; v_course integer; v_active boolean;
begin
    select * into a from commerce_accounts where user_id = p_user_id;
    if not found then raise exception 'user_not_registered'; end if;
    select count(*)::integer into v_refs from commerce_accounts where referrer_id = p_user_id and referral_confirmed;
    select coalesce(sum(remaining), 0)::integer into v_free from commerce_grants
        where user_id = p_user_id and service = 'presentation' and expires_at > now();
    select coalesce(sum(remaining), 0)::integer into v_course from commerce_grants
        where user_id = p_user_id and service = 'course';
    v_active := coalesce(a.subscription_end > now(), false);
    return jsonb_build_object('balance', (select coalesce(balance, 0) from users where telegram_id = p_user_id),
        'confirmed_referrals', v_refs, 'next_reward_in', 5 - (v_refs % 5),
        'referral_presentations', v_free, 'course_credits', v_course,
        'subscription_active', v_active, 'subscription_end', a.subscription_end,
        'subscription_remaining', case when v_active then 10 - a.subscription_used else 0 end,
        'presentation_period_active', v_active or exists(select 1 from commerce_grants
            where user_id = p_user_id and service = 'presentation' and expires_at > now()),
        'prices', jsonb_build_object('subscription', 25000, 'presentation', 10000, 'course', 30000,
            'referat', 8000, 'article', 10000), 'payment_card', '9860020144204623');
end $$;

create or replace function public.commerce_subscribe(p_user_id bigint)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_balance numeric; v_end timestamptz;
begin
    perform 1 from commerce_accounts where user_id = p_user_id for update;
    if not found then raise exception 'user_not_registered'; end if;
    select subscription_end into v_end from commerce_accounts where user_id = p_user_id;
    if v_end > now() then raise exception 'subscription_active'; end if;
    select coalesce(balance, 0) into v_balance from users where telegram_id = p_user_id for update;
    if v_balance < 25000 then raise exception 'insufficient_balance'; end if;
    update users set balance = v_balance - 25000 where telegram_id = p_user_id;
    update commerce_accounts set subscription_start = now(), subscription_end = now() + interval '1 month',
        subscription_used = 0 where user_id = p_user_id;
    insert into statistics(user_id, action_type, amount) values(p_user_id, 'subscription', 25000);
    return commerce_status(p_user_id);
end $$;

create or replace function public.commerce_reserve(p_user_id bigint, p_service text, p_request_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare a commerce_accounts%rowtype; c commerce_charges%rowtype; g commerce_grants%rowtype;
    v_source text := 'balance'; v_price numeric; v_balance numeric;
begin
    -- Same account lock is used by referrals, purchases, reservations and refunds.
    select * into a from commerce_accounts where user_id = p_user_id for update;
    if not found then raise exception 'user_not_registered'; end if;
    select * into c from commerce_charges where id = p_request_id;
    if found then
        if c.user_id <> p_user_id or c.service <> p_service then raise exception 'request_conflict'; end if;
        return to_jsonb(c) || jsonb_build_object('created', false);
    end if;
    v_price := case p_service when 'presentation' then 10000 when 'course' then 30000
        when 'referat' then 8000 when 'article' then 10000 when 'design' then 5000 when 'obyektivka' then 10000 else null end;
    if v_price is null then raise exception 'invalid_service'; end if;
    -- Paid allowance first, then expiring referral credits; neither is counted twice.
    if p_service = 'presentation' and a.subscription_end > now() and a.subscription_used < 10 then
        update commerce_accounts set subscription_used = subscription_used + 1 where user_id = p_user_id;
        v_source := 'subscription'; v_price := 0;
    elsif p_service in ('presentation', 'course') then
        select * into g from commerce_grants where user_id = p_user_id and service = p_service
            and remaining > 0 and (expires_at is null or expires_at > now())
            order by expires_at nulls last, created_at, id limit 1 for update;
        if found then
            update commerce_grants set remaining = remaining - 1 where id = g.id;
            v_source := 'referral'; v_price := 0;
        elsif p_service = 'presentation' and not coalesce(a.subscription_end > now(), false)
            and not exists(select 1 from commerce_grants where user_id = p_user_id
                and service = 'presentation' and expires_at > now()) then
            raise exception 'presentation_access_required';
        end if;
    end if;
    if v_source = 'balance' then
        select coalesce(balance, 0) into v_balance from users where telegram_id = p_user_id for update;
        if v_balance < v_price then raise exception 'insufficient_balance'; end if;
        update users set balance = v_balance - v_price where telegram_id = p_user_id;
    end if;
    insert into commerce_charges(id, user_id, service, source, amount, grant_id, subscription_start)
        values(p_request_id, p_user_id, p_service, v_source, v_price, g.id,
            case when v_source = 'subscription' then a.subscription_start else null end)
        returning * into c;
    return to_jsonb(c) || jsonb_build_object('created', true);
end $$;

create or replace function public.commerce_finish(p_user_id bigint, p_request_id uuid, p_success boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c commerce_charges%rowtype;
begin
    perform 1 from commerce_accounts where user_id = p_user_id for update;
    select * into c from commerce_charges where id = p_request_id and user_id = p_user_id for update;
    if not found then raise exception 'charge_not_found'; end if;
    if c.status <> 'reserved' then return to_jsonb(c); end if;
    if not p_success then
        if c.source = 'balance' then
            update users set balance = coalesce(balance, 0) + c.amount where telegram_id = p_user_id;
        elsif c.source = 'referral' then
            update commerce_grants set remaining = remaining + 1 where id = c.grant_id;
        else
            update commerce_accounts set subscription_used = greatest(subscription_used - 1, 0)
                where user_id = p_user_id and subscription_start = c.subscription_start;
        end if;
    else
        insert into statistics(user_id, action_type, amount)
            values(p_user_id, case when c.service = 'course' then 'course_work' else c.service end, c.amount);
    end if;
    update commerce_charges set status = case when p_success then 'completed' else 'refunded' end,
        updated_at = now() where id = p_request_id returning * into c;
    return to_jsonb(c);
end $$;

create or replace function public.commerce_heartbeat(p_user_id bigint, p_request_id uuid)
returns boolean language plpgsql security definer set search_path = public as $$
begin
    update commerce_charges set lease_until = now() + interval '3 minutes'
        where id = p_request_id and user_id = p_user_id and status = 'reserved';
    return found;
end $$;

create or replace function public.commerce_enqueue(p_user_id bigint, p_service text, p_request_id uuid, p_payload jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_charge jsonb;
begin
    if p_service not in ('presentation', 'article') then raise exception 'invalid_service'; end if;
    v_charge := commerce_reserve(p_user_id, p_service, p_request_id);
    if (v_charge->>'created')::boolean then
        insert into commerce_jobs(id, user_id, service, payload) values(p_request_id, p_user_id, p_service, p_payload);
    elsif not exists(select 1 from commerce_jobs where id = p_request_id and
        (payload - 'user_images') = (p_payload - 'user_images')) then
        raise exception 'request_conflict';
    end if;
    return v_charge;
end $$;

create or replace function public.commerce_claim_job(p_worker_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare j commerce_jobs%rowtype;
begin
    select * into j from commerce_jobs where status = 'queued' or
        (status = 'processing' and lease_until < now())
        order by created_at limit 1 for update skip locked;
    if not found then return null; end if;
    update commerce_jobs set status = 'processing', worker_id = p_worker_id, attempts = attempts + 1,
        lease_until = now() + interval '3 minutes', updated_at = now() where id = j.id returning * into j;
    return to_jsonb(j);
end $$;

create or replace function public.commerce_job_heartbeat(p_request_id uuid, p_worker_id uuid)
returns boolean language plpgsql security definer set search_path = public as $$
begin
    update commerce_jobs set lease_until = now() + interval '3 minutes'
        where id = p_request_id and worker_id = p_worker_id and status = 'processing';
    return found;
end $$;

create or replace function public.commerce_finish_job(p_request_id uuid, p_worker_id uuid,
    p_success boolean, p_result jsonb default null, p_error text default null)
returns boolean language plpgsql security definer set search_path = public as $$
declare j commerce_jobs%rowtype;
begin
    select * into j from commerce_jobs where id = p_request_id for update;
    if not found or j.worker_id is distinct from p_worker_id or j.status <> 'processing' then return false; end if;
    perform commerce_finish(j.user_id, j.id, p_success);
    update commerce_jobs set status = case when p_success then 'completed' else 'failed' end,
        result = p_result, error = left(p_error, 1000), updated_at = now() where id = j.id;
    return true;
end $$;

create or replace function public.commerce_recover_expired()
returns integer language plpgsql security definer set search_path = public as $$
declare c record; v_count integer := 0;
begin
    -- Bot generation has no queue entry. A lost worker must not permanently consume a credit.
    for c in select id, user_id from commerce_charges where status = 'reserved' and lease_until < now()
        and not exists(select 1 from commerce_jobs where commerce_jobs.id = commerce_charges.id)
    loop
        perform commerce_finish(c.user_id, c.id, false); v_count := v_count + 1;
    end loop;
    return v_count;
end $$;

create or replace function public.commerce_approve_payment(p_payment_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare p payments%rowtype; v_end timestamptz;
begin
    select * into p from payments where id::text = p_payment_id for update;
    if not found or p.status <> 'pending' then return null; end if;
    if p.amount <= 0 then raise exception 'invalid_amount'; end if;
    begin
        if p.receipt_hash is not null then
            insert into commerce_receipt_keys(kind, key, user_id, payment_id)
                values('hash', p.receipt_hash, p.user_id, p_payment_id);
        end if;
        if p.receipt_tx is not null then
            insert into commerce_receipt_keys(kind, key, user_id, payment_id)
                values('tx', p.receipt_tx, p.user_id, p_payment_id);
        end if;
    exception when unique_violation then
        raise exception 'duplicate_receipt';
    end;
    perform 1 from commerce_accounts where user_id = p.user_id for update;
    if not found then raise exception 'user_not_registered'; end if;
    -- Receipt image analysis is advisory; ONLY an authorized admin calls this function.
    if p.purpose = 'subscription' then
        if p.amount <> 25000 then raise exception 'invalid_amount'; end if;
        select subscription_end into v_end from commerce_accounts where user_id = p.user_id;
        if v_end > now() then
            -- Another payment already activated this month: preserve the second payment as balance.
            update users set balance = coalesce(balance, 0) + p.amount where telegram_id = p.user_id;
        else
            update commerce_accounts set subscription_start = now(), subscription_end = now() + interval '1 month',
                subscription_used = 0 where user_id = p.user_id;
        end if;
    elsif p.purpose = 'topup' then
        update users set balance = coalesce(balance, 0) + p.amount where telegram_id = p.user_id;
    else
        raise exception 'invalid_payment_purpose';
    end if;
    update payments set status = 'completed' where id::text = p_payment_id;
    insert into statistics(user_id, action_type, amount) values(p.user_id, 'topup', p.amount);
    return to_jsonb(p) || jsonb_build_object('status', 'completed');
end $$;

create or replace function public.commerce_reject_payment(p_payment_id text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare p payments%rowtype;
begin
    update payments set status = 'rejected' where id::text = p_payment_id and status = 'pending' returning * into p;
    if not found then return null; end if;
    return to_jsonb(p);
end $$;

-- No client-supplied user ID can invoke a billing/referral RPC through the public anon API.
do $$ declare f record; t text; begin
    for f in select oid::regprocedure as signature from pg_proc
        where pronamespace = 'public'::regnamespace and proname like 'commerce_%'
    loop
        execute format('revoke all on function %s from public, anon, authenticated', f.signature);
        execute format('grant execute on function %s to service_role', f.signature);
    end loop;
    foreach t in array array['users', 'payments', 'statistics', 'commerce_accounts', 'commerce_grants', 'commerce_charges', 'commerce_jobs', 'commerce_receipt_keys'] loop
        execute format('alter table public.%I enable row level security', t);
        execute format('revoke all on table public.%I from public, anon, authenticated', t);
        execute format('grant all on table public.%I to service_role', t);
    end loop;
end $$;

grant usage, select on all sequences in schema public to service_role;

commit;
